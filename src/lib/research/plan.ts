export function impactForIndustry(industry: string) {
  return IMPACTS.find((i) => i.industry === industry);
}

export function dirTone(dir: Direction): "steel" | "neutral" | "warn" {
  if (dir === "受益") return "steel";
  if (dir === "约束") return "warn";
  return "neutral";
}

export function dirScore(dir: Direction) {
  if (dir === "受益") return 78;
  if (dir === "约束") return 26;
  return 50;
}

export function planScores(industry: string) {
  const row = impactForIndustry(industry);
  const p5 = dirScore(row?.y5.dir ?? "中性");
  const p10 = dirScore(row?.y10.dir ?? "中性");
  return {
    p5,
    p10,
    pDay: 0.55 * p5 + 0.45 * 50,
    pMonth: 0.7 * p5 + 0.3 * p10,
    pYear: 0.32 * p5 + 0.68 * p10,
    dir5: row?.y5.dir ?? "中性",
    dir10: row?.y10.dir ?? "中性",
  };
}
